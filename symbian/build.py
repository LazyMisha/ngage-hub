"""Build one Python 2.2 script for transfer to the N-Gage."""

import argparse
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
HUB_MODULES = ("__init__", "bitmap", "pixel_font", "mock_weather", "sunset",
               "day_cycle", "dashboard")

# PyS60's Inbox can install one script at a time. Keep the shared modules
# in separate namespaces inside that file and restore the script shell's imports.
LOADER = '''import sys


def run_ngage(sources, launcher, keep_awake):
    previous = []
    try:
        for name, path, source in sources:
            previous.append((name, sys.modules.get(name)))
            module = type(sys)(name)
            module.__name__ = name
            module.__file__ = path
            sys.modules[name] = module
            if name == "hub":
                module.__path__ = []
            else:
                setattr(sys.modules["hub"], name.split(".")[-1], module)
            eval(compile(source, path, "exec"), module.__dict__)
        entry = {"__name__": "ngage_phone"}
        eval(compile(launcher, "symbian/launcher.py", "exec"), entry)
        entry["main"](keep_awake)
    finally:
        for name, module in previous:
            if module is not None:
                sys.modules[name] = module
            elif name in sys.modules:
                del sys.modules[name]
'''


def source_literal(path, indent):
    source = (ROOT / path).read_text(encoding="ascii")
    compile(source, path, "exec")
    return "\n".join(indent + repr(line) for line in source.splitlines(keepends=True))


def binary_literal(path, indent):
    data = (ROOT / path).read_bytes()
    return "\n".join(
        indent + '"' + "".join(f"\\x{value:02x}" for value in data[offset:offset + 24]) + '"'
        for offset in range(0, len(data), 24)
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("output", nargs="?", type=Path, default=ROOT / "build" / "ngage_hub.py")
    output = parser.parse_args().output

    sections = ["# Generated by symbian/build.py. Transfer this file to the handset.",
                LOADER.rstrip(), "run_ngage(("]
    for module in HUB_MODULES:
        name = "hub" if module == "__init__" else f"hub.{module}"
        path = f"hub/{module}.py"
        sections.extend((f"    ({name!r}, {path!r},",
                         source_literal(path, "        "), "    ),"))
    sections.extend(("), (", source_literal("symbian/launcher.py", "    "),
                     "), (", binary_literal("symbian/_ngageawake_v1.pyd", "    "),
                     "))", ""))
    bundle = "\n".join(sections)
    compile(bundle, output.name, "exec")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(bundle, encoding="ascii")
    print(output.resolve())


if __name__ == "__main__":
    main()
